import { readdir, realpath, stat } from "node:fs/promises";
import { isAbsolute, join, resolve } from "node:path";
import type { Masker } from "./mask.ts";
import { findingId } from "./secret.ts";

export type GitHook = {
  id: string;
  project: string;
  hook: string;
  path: string;
  hooksPath: string | null;
  manager: string | null;
};

const HOOKS = new Set([
  "applypatch-msg",
  "pre-applypatch",
  "post-applypatch",
  "pre-commit",
  "pre-merge-commit",
  "prepare-commit-msg",
  "commit-msg",
  "post-commit",
  "pre-rebase",
  "post-checkout",
  "post-merge",
  "pre-push",
  "pre-receive",
  "update",
  "proc-receive",
  "post-receive",
  "post-update",
  "reference-transaction",
  "push-to-checkout",
  "pre-auto-gc",
  "post-rewrite",
  "sendemail-validate",
  "fsmonitor-watchman",
  "p4-changelist",
  "p4-prepare-changelist",
  "p4-post-changelist",
  "p4-pre-submit",
  "post-index-change",
]);

const MANAGERS: [RegExp, string][] = [
  [/husky|\$\(dirname "\$0"\)\/h"/i, "husky"],
  [/lefthook/i, "lefthook"],
  [/File generated by pre-commit|pre_commit|pre-commit\.com/i, "pre-commit"],
  [/simple-git-hooks/i, "simple-git-hooks"],
  [/overcommit/i, "overcommit"],
  [/yorkie/i, "yorkie"],
  [/git lfs|git-lfs/i, "git-lfs"],
  [/\bbd hooks?\b|beads/i, "beads"],
];

export async function gitHooks(projects: readonly string[], mask: Masker): Promise<GitHook[]> {
  const seen = new Set<string>();
  const found: GitHook[] = [];
  for (const project of projects) {
    const dir = await git(project, "rev-parse", "--path-format=absolute", "--git-path", "hooks");
    if (!dir) continue;
    const configured = await git(project, "config", "--get", "core.hooksPath");
    const hooksPath = configured
      ? isAbsolute(configured)
        ? configured
        : resolve(project, configured)
      : null;
    for (const name of await readdir(dir).catch(() => [])) {
      if (!HOOKS.has(name)) continue;
      const path = join(dir, name);
      const real = await realpath(path).catch(() => path);
      if (seen.has(real) || !(await executable(path))) continue;
      seen.add(real);
      const head = await Bun.file(path)
        .slice(0, 8192)
        .text()
        .catch(() => "");
      const manager = MANAGERS.find(([marker]) => marker.test(head))?.[1] ?? null;
      found.push({
        id: findingId(mask, "hook", real),
        project,
        hook: name,
        path,
        hooksPath,
        manager,
      });
    }
  }
  return found;
}

async function executable(path: string): Promise<boolean> {
  const info = await stat(path).catch(() => null);
  if (!info?.isFile()) return false;
  return process.platform === "win32" || (info.mode & 0o111) !== 0;
}

async function git(dir: string, ...args: string[]): Promise<string | null> {
  const proc = Bun.spawn(["git", "-C", dir, ...args], { stdout: "pipe", stderr: "ignore" });
  const [out, code] = await Promise.all([new Response(proc.stdout).text(), proc.exited]);
  return code === 0 && out.trim() ? out.trim() : null;
}
